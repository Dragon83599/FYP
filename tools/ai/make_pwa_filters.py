#!/usr/bin/env python3
"""Generate the polyphase resampler coefficients the PWA needs, from scipy.

The browser has to reproduce ``scipy.signal.resample_poly(x, 1, 8)`` exactly,
otherwise the "same wav, <1e-3" acceptance check measures the resampler instead
of the model.  Re-deriving scipy's FIR in JavaScript is not practical, so this
script designs it once and writes it out as an ES module:

    pwa/filters/resample-poly.js

The generator re-implements the relevant part of ``resample_poly`` (``up=1``,
``down=8``, default ``window=('kaiser', 5.0)``) and **verifies itself against
scipy on a real Yaseen clip** before writing anything, so a scipy version change
that alters the filter fails here rather than silently in the browser.

    .venv/bin/python tools/ai/make_pwa_filters.py
    .venv/bin/python tools/ai/make_pwa_filters.py --check   # verify only
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from scipy.signal import firwin, resample_poly

UP, DOWN = 1, 8
HALF_LEN = 10 * max(UP, DOWN)            # scipy: half_len = 10 * max(up, down)
TOLERANCE = 1e-12                        # float64 agreement on a real clip
DEFAULT_OUT = Path("pwa/filters/resample-poly.js")
DEFAULT_CLIP = Path("data/raw/yaseen/extracted/AS/New_AS_001.wav")


def design() -> tuple[np.ndarray, int, int]:
    """Return (padded FIR taps, number of leading zeros, samples to trim)."""
    h = firwin(2 * HALF_LEN + 1, 1.0 / max(UP, DOWN), window=("kaiser", 5.0)) * UP
    n_pre_pad = DOWN - HALF_LEN % DOWN          # put output samples at the centre
    n_pre_remove = (HALF_LEN + n_pre_pad) // DOWN
    return np.concatenate([np.zeros(n_pre_pad), h]), n_pre_pad, n_pre_remove


def resample_js_equivalent(x: np.ndarray, h_padded: np.ndarray, n_pre_remove: int) -> np.ndarray:
    """What ``pwa/preprocess.js`` does: full convolution, decimate, trim."""
    n_in = x.shape[0]
    n_out = n_in // DOWN + (1 if n_in % DOWN else 0)
    y = np.convolve(x, h_padded)[::DOWN]
    return y[n_pre_remove : n_pre_remove + n_out]


def verify(h_padded: np.ndarray, n_pre_remove: int, clip: Path) -> float:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from repro_ma2023 import read_wav_mono

    x, fs = read_wav_mono(clip)
    if fs != 8_000:
        raise SystemExit(f"{clip} is {fs} Hz, expected the 8 kHz Yaseen rate")
    reference = resample_poly(x, UP, DOWN)
    got = resample_js_equivalent(x, h_padded, n_pre_remove)
    if reference.shape != got.shape:
        raise SystemExit(f"length mismatch: scipy {reference.shape} vs JS-equivalent {got.shape}")
    return float(np.max(np.abs(reference - got)))


def render(h_padded: np.ndarray, n_pre_remove: int) -> str:
    lines = [
        "// Generated by tools/ai/make_pwa_filters.py -- do not edit by hand.",
        "// scipy.signal.resample_poly(x, up=1, down=8), default window=('kaiser', 5.0):",
        f"// firwin({2 * HALF_LEN + 1}, 1/8) with {len(h_padded) - (2 * HALF_LEN + 1)} leading zeros.",
        "// pwa/preprocess.js reproduces scipy with a full convolution + decimation +",
        "// trim; tools/ai/make_pwa_filters.py checks that agreement on a real clip.",
        f"export const RESAMPLE_UP = {UP};",
        f"export const RESAMPLE_DOWN = {DOWN};",
        f"export const N_PRE_REMOVE = {n_pre_remove};",
        "export const H_PADDED = [",
    ]
    for start in range(0, len(h_padded), 4):
        chunk = ", ".join(f"{value:.17g}" for value in h_padded[start : start + 4])
        lines.append(f"  {chunk},")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--clip", type=Path, default=DEFAULT_CLIP,
                        help="real 8 kHz clip used to verify the reimplementation")
    parser.add_argument("--check", action="store_true",
                        help="verify against scipy and the existing file, write nothing")
    args = parser.parse_args(argv)

    h_padded, n_pre_pad, n_pre_remove = design()
    error = verify(h_padded, n_pre_remove, args.clip)
    print(f"scipy vs JS-equivalent on {args.clip.name}: max |diff| = {error:.3e}")
    if error > TOLERANCE:
        raise SystemExit(f"reimplementation disagrees with scipy by {error:.3e} > {TOLERANCE:.0e}")

    text = render(h_padded, n_pre_remove)
    if args.check:
        if not args.out.exists():
            raise SystemExit(f"{args.out} does not exist; run without --check to create it")
        if args.out.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{args.out} is stale; re-run without --check")
        print(f"{args.out} is up to date ({len(h_padded)} taps, trim {n_pre_remove})")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(h_padded)} taps, trim {n_pre_remove})")
    return 0


if __name__ == "__main__":
    sys.exit(main())

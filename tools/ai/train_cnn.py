#!/usr/bin/env python3
"""Train the small 1D CNN on raw heart-sound windows and measure its budget.

The same patient-level split generated by ``prepare_circor.py`` is used. This
script reports parameters, INT8 size, MACs, PC latency and quantized metrics.
It does not claim target-board performance: that still has to be measured on
the selected host MCU.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from collections import defaultdict
from pathlib import Path

import numpy as np
import torch
from torch import nn
from torch.utils.data import DataLoader, Dataset

from hs_cnn import (
    Small1DCNN,
    count_parameters,
    export_onnx,
    measure_latency,
    measure_macs,
    quantize_onnx_static,
)
from hs_features import design_bandpass_fir, filtfilt, iter_windows, read_wav_mono
from hs_metrics import best_threshold, binary_metrics, bootstrap_ci
from hs_segments import annotated_window_starts, load_segments


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", default="data/processed/circor-subset")
    parser.add_argument("--out-dir", default="data/reports/circor-cnn")
    parser.add_argument("--window-sec", type=float, default=2.0)
    parser.add_argument("--hop-sec", type=float, default=1.0)
    parser.add_argument("--max-windows-per-record", type=int, default=4)
    parser.add_argument("--epochs", type=int, default=40)
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--patience", type=int, default=8)
    parser.add_argument("--seed", type=int, default=20261007)
    parser.add_argument("--windows-per-second", type=float, default=0.5)
    parser.add_argument(
        "--window-selection",
        choices=("all", "annotated"),
        default="all",
        help="Use every window, or only windows covered by CirCor segmentation labels.",
    )
    parser.add_argument("--min-annotated-fraction", type=float, default=0.5)
    parser.add_argument("--rebuild-cache", action="store_true")
    parser.add_argument("--skip-onnx", action="store_true")
    return parser.parse_args()


class WindowDataset(Dataset):
    def __init__(self, windows: np.ndarray, labels: np.ndarray) -> None:
        self.windows = windows
        self.labels = labels

    def __len__(self) -> int:
        return len(self.labels)

    def __getitem__(self, index: int):
        window = self.windows[index].astype(np.float32)
        return torch.from_numpy(window), torch.tensor(float(self.labels[index]))


def load_recordings(data_dir: Path) -> list[dict]:
    with (data_dir / "recordings.csv").open(newline="", encoding="utf-8") as handle:
        rows = [row for row in csv.DictReader(handle)]
    return [row for row in rows if row["split"] in ("train", "val", "test") and row["label"] in ("0", "1")]


def build_cache(data_dir: Path, args: argparse.Namespace) -> tuple[dict, dict]:
    rows = load_recordings(data_dir)
    cache = {
        split: {"x": [], "y": [], "subject": [], "record": []}
        for split in ("train", "val", "test")
    }
    started = time.time()
    skipped_unannotated = 0
    for index, row in enumerate(rows, start=1):
        signal, sample_rate = read_wav_mono(row["wav_path"])
        signal = filtfilt(signal, design_bandpass_fir(sample_rate))
        window_samples = int(round(args.window_sec * sample_rate))
        hop_samples = int(round(args.hop_sec * sample_rate))
        window_items = [
            (start, window)
            for start, window in iter_windows(signal, window_samples, hop_samples)
        ]
        if args.window_selection == "annotated":
            segments = load_segments(row.get("tsv_path", ""))
            allowed = set(
                annotated_window_starts(
                    len(signal),
                    segments,
                    sample_rate,
                    window_samples,
                    hop_samples,
                    args.min_annotated_fraction,
                ).tolist()
            )
            kept = []
            for start, window in window_items:
                if start in allowed:
                    kept.append((start, window))
                else:
                    skipped_unannotated += 1
            window_items = kept
        if args.max_windows_per_record and len(window_items) > args.max_windows_per_record:
            positions = np.linspace(
                0, len(window_items) - 1, args.max_windows_per_record
            ).round().astype(int)
            window_items = [window_items[position] for position in positions]
        bucket = cache[row["split"]]
        for _, window in window_items:
            if float(np.sqrt(np.mean(window**2))) < 1e-4:
                continue
            bucket["x"].append(window.astype(np.float16))
            bucket["y"].append(int(row["label"]))
            bucket["subject"].append(row["subject_id"])
            bucket["record"].append(row["record_id"])
        if index % 100 == 0 or index == len(rows):
            print(
                f"[cache] {index}/{len(rows)} recordings, "
                f"{sum(len(cache[s]['y']) for s in cache)} windows, {time.time() - started:.0f}s"
            )

    result: dict = {}
    for split, bucket in cache.items():
        x = np.stack(bucket["x"]) if bucket["x"] else np.zeros((0, 8000), dtype=np.float16)
        result[split] = {
            "x": x,
            "y": np.asarray(bucket["y"], dtype=np.int8),
            "subject": np.asarray(bucket["subject"]),
            "record": np.asarray(bucket["record"]),
        }
    return result, {"skipped_unannotated": skipped_unannotated}


def save_cache(data_dir: Path, cache: dict, stats: dict) -> None:
    (data_dir / "windows-stats.json").write_text(
        json.dumps(stats, indent=2) + "\n", encoding="utf-8"
    )
    for split in ("train", "val", "test"):
        bucket = cache[split]
        np.save(data_dir / f"windows-{split}.npy", bucket["x"])
        np.savez(
            data_dir / f"windows-{split}-meta.npz",
            y=bucket["y"],
            subject=bucket["subject"],
            record=bucket["record"],
        )


def load_saved_cache(data_dir: Path) -> dict:
    stats_path = data_dir / "windows-stats.json"
    cache = {}
    for split in ("train", "val", "test"):
        x = np.load(data_dir / f"windows-{split}.npy", mmap_mode="r")
        meta = np.load(data_dir / f"windows-{split}-meta.npz", allow_pickle=True)
        cache[split] = {
            "x": x,
            "y": meta["y"],
            "subject": meta["subject"],
            "record": meta["record"],
        }
    if stats_path.exists():
        cache["_stats"] = json.loads(stats_path.read_text(encoding="utf-8"))
    else:
        cache["_stats"] = {}
    return cache


def predict(model: nn.Module, windows: np.ndarray, batch_size: int = 128) -> np.ndarray:
    model.eval()
    probabilities = []
    with torch.no_grad():
        for start in range(0, len(windows), batch_size):
            batch = windows[start : start + batch_size].astype(np.float32)
            logits = model(torch.from_numpy(batch))
            probabilities.append(torch.sigmoid(logits).numpy())
    return np.concatenate(probabilities) if probabilities else np.zeros(0)


def patient_level(probabilities: np.ndarray, labels: np.ndarray, subjects: np.ndarray, threshold: float) -> dict:
    grouped: dict[str, list[float]] = defaultdict(list)
    for subject, probability in zip(subjects, probabilities):
        grouped[subject].append(float(probability))
    subject_ids = sorted(grouped)
    aggregated = np.asarray([np.mean(grouped[subject]) for subject in subject_ids])
    subject_true = np.asarray(
        [int(labels[subjects == subject][0]) for subject in subject_ids], dtype=int
    )
    metrics = binary_metrics(subject_true, aggregated, threshold)
    metrics["auroc_ci95"] = bootstrap_ci(subject_true, aggregated, "auroc")
    metrics["balanced_accuracy_ci95"] = bootstrap_ci(
        subject_true, aggregated, "balanced_accuracy", threshold
    )
    return metrics


def train_model(cache: dict, args: argparse.Namespace) -> tuple[nn.Module, dict]:
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    train = cache["train"]
    val = cache["val"]
    model = Small1DCNN()
    positives = max(int(np.sum(train["y"] == 1)), 1)
    negatives = max(int(np.sum(train["y"] == 0)), 1)
    criterion = nn.BCEWithLogitsLoss(pos_weight=torch.tensor([negatives / positives]))
    optimizer = torch.optim.Adam(
        model.parameters(), lr=args.learning_rate, weight_decay=args.weight_decay
    )
    loader = DataLoader(
        WindowDataset(train["x"], train["y"]),
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=0,
    )
    best_state = None
    best_score = -1.0
    best_epoch = 0
    history = []
    stale_epochs = 0

    for epoch in range(1, args.epochs + 1):
        model.train()
        losses = []
        for windows, labels in loader:
            optimizer.zero_grad()
            logits = model(windows)
            loss = criterion(logits, labels)
            loss.backward()
            optimizer.step()
            losses.append(float(loss.item()))
        val_probabilities = predict(model, val["x"])
        val_metrics = patient_level(val_probabilities, val["y"], val["subject"], 0.5)
        val_window_metrics = binary_metrics(val["y"], val_probabilities, 0.5)
        score = val_window_metrics["auroc"]
        history.append(
            {
                "epoch": epoch,
                "loss": float(np.mean(losses)),
                "val_window_auroc": score,
                "val_patient_auroc": val_metrics["auroc"],
                "val_patient_balanced_accuracy": val_metrics["balanced_accuracy"],
            }
        )
        print(
            f"[train] epoch {epoch:3d} loss={np.mean(losses):.4f} "
            f"val_window_auroc={score:.3f} "
            f"val_patient_auroc={val_metrics['auroc']:.3f} "
            f"bal_acc={val_metrics['balanced_accuracy']:.3f}"
        )
        if score > best_score:
            best_score = score
            best_epoch = epoch
            best_state = {key: value.detach().clone() for key, value in model.state_dict().items()}
            stale_epochs = 0
        else:
            stale_epochs += 1
            if stale_epochs >= args.patience:
                print(f"[train] early stop at epoch {epoch}")
                break

    if best_state is not None:
        model.load_state_dict(best_state)
    return model, {"best_epoch": best_epoch, "best_val_window_auroc": best_score, "history": history}


def evaluate(model: nn.Module, cache: dict, args: argparse.Namespace) -> dict:
    probabilities = {
        split: predict(model, cache[split]["x"]) for split in ("train", "val", "test")
    }
    threshold, val_score = best_threshold(cache["val"]["y"], probabilities["val"])
    result = {
        "threshold": threshold,
        "val_balanced_accuracy_at_threshold": val_score,
        "window_level": {},
        "patient_level": {},
    }
    for split in ("train", "val", "test"):
        bucket = cache[split]
        result["window_level"][split] = binary_metrics(
            bucket["y"], probabilities[split], threshold
        )
        result["patient_level"][split] = patient_level(
            probabilities[split], bucket["y"], bucket["subject"], threshold
        )
    return result


def onnx_runtime_latency(path: Path, input_length: int, runs: int = 100) -> dict:
    import onnxruntime as ort

    session = ort.InferenceSession(str(path), providers=["CPUExecutionProvider"])
    input_name = session.get_inputs()[0].name
    sample = np.zeros((1, input_length), dtype=np.float32)
    for _ in range(10):
        session.run(None, {input_name: sample})
    timings = []
    for _ in range(runs):
        started = time.perf_counter()
        session.run(None, {input_name: sample})
        timings.append((time.perf_counter() - started) * 1000.0)
    values = np.asarray(timings)
    return {
        "runs": runs,
        "mean_ms": float(values.mean()),
        "p95_ms": float(np.percentile(values, 95)),
        "max_ms": float(values.max()),
    }


def onnx_predict(path: Path, windows: np.ndarray, batch_size: int = 128) -> np.ndarray:
    import onnxruntime as ort

    session = ort.InferenceSession(str(path), providers=["CPUExecutionProvider"])
    input_name = session.get_inputs()[0].name
    outputs = []
    for start in range(0, len(windows), batch_size):
        batch = windows[start : start + batch_size].astype(np.float32)
        logits = session.run(None, {input_name: batch})[0]
        outputs.append(1.0 / (1.0 + np.exp(-logits)))
    return np.concatenate(outputs).reshape(-1) if outputs else np.zeros(0)


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    args = parse_args()
    data_dir = Path(args.data_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    cache_file = data_dir / "windows-train.npy"
    if cache_file.exists() and not args.rebuild_cache:
        cache = load_saved_cache(data_dir)
    else:
        cache, stats = build_cache(data_dir, args)
        save_cache(data_dir, cache, stats)
        cache["_stats"] = stats
    print(
        "[cache] train/val/test windows: "
        + ", ".join(f"{split}={len(cache[split]['y'])}" for split in ("train", "val", "test"))
    )

    model, training = train_model(cache, args)
    evaluation = evaluate(model, cache, args)
    parameters = count_parameters(model)
    macs = measure_macs(model, input_length=cache["train"]["x"].shape[1])
    latency = measure_latency(model, input_length=cache["train"]["x"].shape[1])
    fp32_bytes = sum(value.numel() * value.element_size() for value in model.state_dict().values())

    report: dict = {
        "task": "CirCor murmur Present vs Absent, subject-level split",
        "model": "Small1DCNN (4 conv blocks, global average pool)",
        "window_sec": args.window_sec,
        "hop_sec": args.hop_sec,
        "max_windows_per_record": args.max_windows_per_record,
        "window_selection": args.window_selection,
        "min_annotated_fraction": args.min_annotated_fraction,
        "skipped_unannotated_windows": int(
            cache.get("_stats", {}).get("skipped_unannotated", -1)
        ),
        "windows": {split: int(len(cache[split]["y"])) for split in ("train", "val", "test")},
        "training": training,
        "evaluation": evaluation,
        "budget": {
            "parameters": parameters,
            "fp32_weight_bytes": int(fp32_bytes),
            "int8_weight_bytes_estimate": int(parameters),
            "macs_per_window": int(macs),
            "windows_per_second": args.windows_per_second,
            "macs_per_second": int(macs * args.windows_per_second),
            "pc_torch_latency": latency,
        },
        "quantization": {},
        "evidence_levels": {
            "parameters_and_macs": "E4 engineering estimate from the model graph",
            "pc_latency": "independent local measurement on this PC, not the target MCU",
            "target_board": "pending, must be measured on ESP32-S3/P4 or STM32N6",
        },
    }

    torch.save(model.state_dict(), out_dir / "model.pt")
    if not args.skip_onnx:
        try:
            fp32_path = out_dir / "model-fp32.onnx"
            export_onnx(model, fp32_path, input_length=cache["train"]["x"].shape[1])
            fp32_latency = onnx_runtime_latency(fp32_path, cache["train"]["x"].shape[1])
            fp32_probabilities = onnx_predict(fp32_path, cache["test"]["x"])
            calibration_size = min(200, len(cache["train"]["x"]))
            indices = np.linspace(
                0, len(cache["train"]["x"]) - 1, calibration_size
            ).round().astype(int)
            quantization = {
                "fp32_onnx_bytes": fp32_path.stat().st_size,
                "fp32_onnx_latency": fp32_latency,
                "fp32_test_patient": patient_level(
                    fp32_probabilities,
                    cache["test"]["y"],
                    cache["test"]["subject"],
                    evaluation["threshold"],
                ),
            }
            int8_path = out_dir / "model-int8.onnx"
            try:
                quantize_onnx_static(
                    fp32_path,
                    int8_path,
                    cache["train"]["x"][indices].astype(np.float32),
                )
                int8_probabilities = onnx_predict(int8_path, cache["test"]["x"])
                quantization.update(
                    {
                        "int8_onnx_bytes": int8_path.stat().st_size,
                        "int8_onnx_latency": onnx_runtime_latency(
                            int8_path, cache["train"]["x"].shape[1]
                        ),
                        "int8_test_patient": patient_level(
                            int8_probabilities,
                            cache["test"]["y"],
                            cache["test"]["subject"],
                            evaluation["threshold"],
                        ),
                        "quantization_method": "onnxruntime static QOperator, per-channel QInt8 weights",
                    }
                )
            except Exception as error:  # noqa: BLE001 - static quantization is optional
                quantization["quantization_error"] = f"{type(error).__name__}: {error}"
            report["quantization"] = quantization
        except Exception as error:  # noqa: BLE001 - ONNX export is optional
            report["quantization"] = {"export_error": f"{type(error).__name__}: {error}"}

    (out_dir / "report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    write_markdown(out_dir / "report.md", report)
    write_budget(out_dir / "resource-budget.md", report)
    print(json.dumps(report["evaluation"], indent=2, ensure_ascii=False))
    print(json.dumps(report["budget"], indent=2, ensure_ascii=False))
    print(f"[report] {out_dir / 'report.md'}")


def write_markdown(path: Path, report: dict) -> None:
    lines = [
        "# Small 1D CNN baseline report",
        "",
        f"- Task: {report['task']}",
        f"- Model: {report['model']}",
        f"- Window: {report['window_sec']} s, hop: {report['hop_sec']} s",
        f"- Window selection: {report['window_selection']} "
        f"(min annotated fraction {report['min_annotated_fraction']})",
        f"- Windows: {report['windows']}",
        f"- Best epoch: {report['training']['best_epoch']}",
        f"- Decision threshold from validation: {report['evaluation']['threshold']:.4f}",
        "",
        "| Level | Split | n | Accuracy | Balanced acc. | Sensitivity | Specificity | AUROC | F1 |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for level in ("window_level", "patient_level"):
        for split, metrics in report["evaluation"][level].items():
            lines.append(
                "| {level} | {split} | {n} | {accuracy:.3f} | {balanced_accuracy:.3f} | "
                "{sensitivity:.3f} | {specificity:.3f} | {auroc:.3f} | {f1:.3f} |".format(
                    level=level, split=split, **metrics
                )
            )
    lines.append("")
    lines.append("## Budget snapshot")
    lines.append("")
    budget = report["budget"]
    lines.append(f"- Parameters: {budget['parameters']:,}")
    lines.append(f"- FP32 weights: {budget['fp32_weight_bytes'] / 1024:.1f} KiB")
    lines.append(f"- INT8 weight estimate: {budget['int8_weight_bytes_estimate'] / 1024:.1f} KiB")
    lines.append(f"- MACs per window: {budget['macs_per_window']:,}")
    lines.append(f"- MACs/s at {budget['windows_per_second']} windows/s: {budget['macs_per_second']:,}")
    lines.append(
        f"- PC PyTorch latency: mean {budget['pc_torch_latency']['mean_ms']:.2f} ms, "
        f"P95 {budget['pc_torch_latency']['p95_ms']:.2f} ms"
    )
    if report.get("quantization"):
        quantization = report["quantization"]
        if "int8_onnx_bytes" in quantization:
            lines.append(f"- INT8 ONNX file: {quantization['int8_onnx_bytes'] / 1024:.1f} KiB")
            lines.append(
                f"- PC INT8 ONNX latency: mean {quantization['int8_onnx_latency']['mean_ms']:.2f} ms, "
                f"P95 {quantization['int8_onnx_latency']['p95_ms']:.2f} ms"
            )
        if "quantization_error" in quantization:
            lines.append(f"- Static quantization error: {quantization['quantization_error']}")
        if "export_error" in quantization:
            lines.append(f"- ONNX export error: {quantization['export_error']}")
    lines.append("")
    lines.append(
        "The PC latency is not target-board latency. Target peak RAM, P95 latency, "
        "current and BLE/Wi-Fi coexistence remain pending until a host board is available."
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


